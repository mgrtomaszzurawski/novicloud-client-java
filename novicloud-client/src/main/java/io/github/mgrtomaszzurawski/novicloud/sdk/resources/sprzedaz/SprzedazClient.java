package io.github.mgrtomaszzurawski.novicloud.sdk.resources.sprzedaz;

import io.github.mgrtomaszzurawski.novicloud.sdk.exception.NoviCloudException;
import io.github.mgrtomaszzurawski.novicloud.sdk.exception.NoviCloudNotFoundException;
import io.github.mgrtomaszzurawski.novicloud.sdk.paging.PagedResult;
import io.github.mgrtomaszzurawski.novicloud.sdk.model.Sprzedaz;

/**
 * Client for the {@code sprzedaz} (sales) endpoint of the NoviCloud API.
 *
 * <p>Obtain an instance from
 * {@link io.github.mgrtomaszzurawski.novicloud.sdk.NoviCloudClient} accessors.
 * Implementation lives in the non-exported {@code sdk.internal.resources.sprzedaz}
 * package; external code should depend on this interface only.
 *
 * @since 2.0.0
 */
public interface SprzedazClient {

    /**
     * Returns a lazy paginated result over all sales matching the given filters.
     *
     * @param query filter parameters, or {@code null} for no filtering
     * @return a {@link PagedResult} of matching records (pages fetched on demand)
     * @throws NoviCloudException on API failure (thrown when the iterator fetches each page)
     */
    PagedResult<Sprzedaz> list(SprzedazQueryBuilder query);

    /**
     * Returns the total number of sales matching the given filters.
     *
     * @param query filter parameters, or {@code null} for no filtering
     * @return total record count
     * @throws NoviCloudException on API failure
     */
    int count(SprzedazQueryBuilder query);

    /**
     * Fetches a single sales record by its numeric ID.
     *
     * @param id the record ID; must not be {@code null}
     * @return the record; never {@code null}
     * @throws IllegalArgumentException if {@code id} is {@code null}
     * @throws NoviCloudNotFoundException if no sales record with the given ID exists
     * @throws NoviCloudException on other API failure
     */
    Sprzedaz getById(Long id);
}
